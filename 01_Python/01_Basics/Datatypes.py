#1.Numeric datatypes isused to store numerical values.
age=23                                      #int datatype
salary=50000.50                             #float datatype
complex_num=5+4j                            #complex datatype

#2.Text datatype is used to store textual information.
name="python"                               #string datatype
sentence="Python is a Programming Language"

#3.Sequence datatype is used store multiple values in a ordered manner.
marks=[92,93,"java",94,95,3.14]             #list datatype
family_members=(10,20,30)                   #tuple datatype
range(5)                                    #range datatype

#4.Set datatypes is used  to store unique values.
num={12,42,87,28,"python",80.2}             #SetDatatype

#5.Mapping type is used to store the values in key-value pairs.
student_details={                            #dictionary datatype
    "name":"John",
    "age":23,
    "salary":50000.50,
}
